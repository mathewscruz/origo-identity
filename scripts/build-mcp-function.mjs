#!/usr/bin/env node
// Gera supabase/functions/mcp/index.ts a partir de src/lib/mcp/index.ts — mesma saída
// do plugin @lovable.dev/mcp-js (que no Windows trata "C:\..." como pacote npm e quebra).
// No Lovable (Linux) o plugin continua fazendo isso sozinho no build; este script é
// para regenerar localmente no Windows.
//
//   node scripts/build-mcp-function.mjs
import { build } from "esbuild";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { resolve, join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const entry = resolve(root, "src/lib/mcp/index.ts");
const outFile = resolve(root, "supabase/functions/mcp/index.ts");
const functionName = "mcp";

const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
const versions = { ...pkg.peerDependencies, ...pkg.devDependencies, ...pkg.dependencies };
const sdkVersion = JSON.parse(readFileSync(join(root, "node_modules/@lovable.dev/mcp-js/package.json"), "utf8")).version;

function npmSpecifierFor(bare) {
  const name = bare.startsWith("@") ? bare.split("/").slice(0, 2).join("/") : bare.split("/")[0];
  const subpath = bare.slice(name.length);
  if (name === "@lovable.dev/mcp-js") return `npm:${name}@${sdkVersion}${subpath}`;
  const range = versions[name];
  const version = range && /^[\dv^~>=]|^latest$/.test(range) ? range : undefined;
  return version ? `npm:${name}@${version}${subpath}` : `npm:${name}${subpath}`;
}

const externalize = {
  name: "externalize-bare-as-npm",
  setup(b) {
    b.onResolve({ filter: /.*/ }, (args) => {
      const p = args.path;
      // caminhos locais: relativos, absolutos POSIX e absolutos Windows (a correção)
      if (p.startsWith(".") || p.startsWith("/") || /^[A-Za-z]:[\\/]/.test(p)) return null;
      if (/^(npm|node|jsr|https?|data):/.test(p)) return { path: p, external: true };
      return { path: npmSpecifierFor(p), external: true };
    });
  },
};

// import.meta.env de PRODUÇÃO: lê .env e .env.production, NUNCA .env.local (o bundle vai para o Lovable Cloud)
function readDotenv(file) {
  const out = {};
  let text = "";
  try { text = readFileSync(file, "utf8"); } catch { return out; }
  for (const rawLine of text.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith("#")) continue;
    const eq = line.indexOf("=");
    if (eq < 0) continue;
    const key = line.slice(0, eq).trim();
    let v = line.slice(eq + 1).trim();
    if ((v.startsWith('"') && v.endsWith('"')) || (v.startsWith("'") && v.endsWith("'"))) v = v.slice(1, -1);
    if (/^[A-Za-z_][A-Za-z0-9_]*$/.test(key)) out[key] = v;
  }
  return out;
}
const rawEnv = { ...readDotenv(join(root, ".env")), ...readDotenv(join(root, ".env.production")) };
const viteEnv = Object.fromEntries(Object.entries(rawEnv).filter(([k]) => k.startsWith("VITE_")));
const env = { ...viteEnv, MODE: "production", BASE_URL: "/", DEV: false, PROD: true, SSR: false };
const define = { "import.meta.env": JSON.stringify(env) };
for (const [k, v] of Object.entries(env)) if (/^[A-Za-z_$][\w$]*$/.test(k)) define[`import.meta.env.${k}`] = JSON.stringify(v);

const wrapper = `import mcp from ${JSON.stringify(entry)};
import { createSupabaseHandler } from "@lovable.dev/mcp-js/stacks/supabase";
Deno.serve(createSupabaseHandler(mcp, { functionName: ${JSON.stringify(functionName)} }));
`;
const result = await build({
  stdin: { contents: wrapper, resolveDir: root, sourcefile: "lovable-mcp-supabase-entry.ts", loader: "ts" },
  bundle: true, write: false, format: "esm", platform: "neutral", target: "esnext",
  absWorkingDir: root, logLevel: "silent", define, plugins: [externalize],
});
const banner = `// AUTO-GENERATED by @lovable.dev/mcp-js \u2014 do not edit. Regenerated by the Vite plugin.
// To take ownership, delete this banner line; the plugin then leaves the file alone.
// supabase function: ${functionName}
// Bundled from src/lib/mcp/index.ts by @lovable.dev/mcp-js.
`;
mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, banner + result.outputFiles[0].text);
console.log(`ok: ${outFile} (${result.outputFiles[0].text.split("\n").length} linhas)`);
